def fwd(route):
    req = urllib.request.Request("http://127.0.0.1:8766", data=(route.request.post_data or "{}").encode(), method="POST")
    try:
        r = urllib.request.urlopen(req); st, body = r.status, r.read()
    except urllib.error.HTTPError as e:
        st, body = e.code, e.read()
    route.fulfill(status=st, content_type="application/json", body=body)
def api(p):
    req = urllib.request.Request("http://127.0.0.1:8766", data=json.dumps(p).encode(), method="POST")
    try: return json.loads(urllib.request.urlopen(req).read())
    except urllib.error.HTTPError as e: return {"_s": e.code, **json.loads(e.read())}
